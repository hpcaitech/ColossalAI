def reinitialize_action_head(model) -> list[str]:
    """Apply DomainAwareLinear's truncated normal (three sigma) and zero bias initializer."""
    touched = []
    for name in ("action_proj_in", "action_proj_out"):
        module = getattr(model, name, None)
        if module is None:
            continue
        std = 1.0 / math.sqrt(module.input_size)
        torch.nn.init.trunc_normal_(module.fc.weight, std=std, a=-3 * std, b=3 * std)
        torch.nn.init.zeros_(module.bias.weight)
        touched.append(name)
    embed = getattr(model, "action_modality_embed", None)
    if embed is not None:
        std = 1.0 / math.sqrt(embed.shape[-1])
        torch.nn.init.trunc_normal_(embed, std=std, a=-3 * std, b=3 * std)
        touched.append("action_modality_embed")
    return touched


def load_action_head(model, path: Path) -> list[str]:
    """Load a full action-head export or an explicitly named domain slice, validating before writing."""
    blob = torch.load(path, map_location="cpu", weights_only=True)
    domain = None
    if blob.get("format") == "action-head-domain-slice":
        domain = int(blob["domain_id"])
        blob = {key: value for key, value in blob.items() if key not in ("format", "domain_id")}
    expected = {
        "action_modality_embed",
        "action2llm.fc.weight",
        "action2llm.bias.weight",
        "llm2action.fc.weight",
        "llm2action.bias.weight",
    }
    if set(blob) != expected:
        raise KeyError(
            f"{path}: action-head keys differ: missing={expected - set(blob)}, unknown={set(blob) - expected}"
        )
    copies = []
    for key, value in blob.items():
        if key == "action_modality_embed":
            target = model.action_modality_embed
        else:
            head, rest = key.split(".", 1)
            owner = {"action2llm": "action_proj_in", "llm2action": "action_proj_out"}[head]
            target = model.get_parameter(f"{owner}.{rest}")
            if domain is not None:
                if not 0 <= domain < target.shape[0]:
                    raise ValueError(f"{path}: invalid domain {domain}")
                target = target[domain]
        if not isinstance(value, torch.Tensor) or target.shape != value.shape:
            raise ValueError(f"{path}: {key} has the wrong tensor shape")
        copies.append((target, value))
    with torch.no_grad():
        for target, value in copies:
            target.copy_(value.to(device=target.device, dtype=target.dtype))
    if domain is not None:
        print(
            f"[model] action head replaced only for domain {domain}; other domains retain their initialization",
            flush=True,
        )
    return list(blob)


def build_model(checkpoint: Path, reinit_action_head: bool = False, action_head_from: Path = None):
    from diffusers import Cosmos3OmniTransformer

    model = Cosmos3OmniTransformer.from_pretrained(checkpoint / "transformer", torch_dtype=torch.bfloat16)
    if reinit_action_head:
        touched = reinitialize_action_head(model)
        if len(touched) != 3:
            raise ValueError(f"The checkpoint does not expose all action heads: {touched}")
        print(f"[model] action head initialized: {', '.join(touched)}", flush=True)
    if action_head_from is not None:
        print(f"[model] loaded action head: {', '.join(load_action_head(model, action_head_from))}", flush=True)
    trainable, frozen = select_trainable_parameters(model)
    print(f"[model] trainable {trainable / 1e9:.3f}B / frozen {frozen / 1e9:.3f}B", flush=True)
    return model


def select_trainable_parameters(model):
    """Apply the recipe's substring rule and return the trainable and frozen element counts."""
    trainable = frozen = 0
    for name, parameter in model.named_parameters():
        parameter.requires_grad = any(key in name for key in TRAINABLE_KEYS)
        if parameter.requires_grad:
            trainable += parameter.numel()
        else:
            frozen += parameter.numel()
    return trainable, frozen


def build_tokenizer(checkpoint: Path):
    from transformers import AutoTokenizer

    return AutoTokenizer.from_pretrained(checkpoint / "text_tokenizer")


def build_vae(
    checkpoint: Path,
    dtype: torch.dtype = torch.bfloat16,
    chunk_frames: int = 0,
    fuse_norm: bool = False,
    fast_encoder: bool = False,
    aot_dir: Path = None,
    *,
    gate_rtol=1e-3,
    gate_atol=None,
    gate_relative_l2=None,
):
    """Load the frozen, online VAE; alternative kernels require explicit opt-in."""
    from diffusers import AutoencoderKLWan

    if get_accelerator().name == "npu":
        torch.npu.conv.allow_hf32 = False
    else:
        torch.backends.cuda.matmul.allow_tf32 = False
        torch.backends.cudnn.allow_tf32 = False
    torch.set_float32_matmul_precision("highest")
    vae = AutoencoderKLWan.from_pretrained(checkpoint / "vae", torch_dtype=dtype).eval().requires_grad_(False)
    if fuse_norm:
        from examples.worldmodel.cosmos3.vae_fused_norm import enable_fused_rmsnorm

        enable_fused_rmsnorm(vae)
    if fast_encoder:
        from examples.worldmodel.cosmos3.vae_fast_encoder import enable_fast_encoder

        enable_fast_encoder(vae)
    if chunk_frames:
        from examples.worldmodel.cosmos3.vae_chunked import enable_chunked_encode

        enable_chunked_encode(
            vae,
            chunk_frames,
            aot_dir=aot_dir,
            verbose=aot_dir is not None,
            gate_rtol=gate_rtol,
            gate_atol=gate_atol,
            gate_relative_l2=gate_relative_l2,
        )
    elif aot_dir is not None:
        raise ValueError("AOT requires a positive chunk_frames value")
    return vae


def build_optimizer(model, choice="hybrid-adam", mode="auto", device_type=None):
    """Keep the recipe parameter groups, independent of the attention backend."""
    base, boosted = [], []
    for name, parameter in model.named_parameters():
        if parameter.requires_grad:
            (boosted if any(key in name for key in LR_MULTIPLIED) else base).append(parameter)
    groups = [
        {"params": base, "lr": LR, "name": "base"},
        {"params": boosted, "lr": LR * 5.0, "name": "action_heads"},
    ]
    kwargs = dict(betas=BETAS, eps=EPS, weight_decay=WEIGHT_DECAY)
    if choice == "hybrid-adam":
        return HybridAdam(groups, adamw_mode=True, **kwargs)
    if choice == "adamw":
        return build_adamw(groups, LR, mode=mode, device_type=device_type, **kwargs)
    raise ValueError(f"Unknown optimizer {choice!r}")


def optimizer_learning_rates(optimizer):
    """Each parameter group's current rate, keyed by the name :func:`build_optimizer` gave it.

    Reading the groups rather than the module constant keeps the metric honest when a schedule is added and when the
    action heads keep their 5x rate.
    """
    return {f"lr/{group.get('name', index)}": group["lr"] for index, group in enumerate(optimizer.param_groups)}


def fix_checkpoint_modes(save_dir: Path, coord: DistCoordinator):
    """Make finished model exports group-readable, after asynchronous writers have joined."""
    if coord.is_master():
        for path in save_dir.rglob("*"):
            os.chmod(path, 0o664 if path.is_file() else 0o775)


def main():
    args = parse_args()
    accelerator = get_accelerator()
    if accelerator.name == "npu":
        importlib.import_module("torch_npu")
    backend = resolve_attention_backend(args.attn_backend, accelerator.name)
    compile_backend = resolve_compile_backend(args.compile_backend, accelerator.name) if args.compile_blocks else None
    vae_backend = (
        resolve_compile_backend(args.compile_vae_backend, accelerator.name) if args.vae_compile == "jit" else None
    )
    if args.vae_compile == "aot" and accelerator.name != "cuda":
        raise ValueError("VAE AOTInductor packages require CUDA")
    if args.optimizer == "adamw" and args.adamw_mode == "fused" and accelerator.name != "npu":
        raise ValueError("The fused AdamW arm requires an NPU")
    colossalai.launch_from_torch(backend=accelerator.communication_backend, seed=args.seed)
    coord = DistCoordinator()
    device = accelerator.get_current_device()
    if coord.world_size % args.sp_size:
        raise ValueError("--sp-size must divide world size")
    if args.zero_stage > 0 and coord.world_size == 1:
        raise ValueError("Use --zero-stage 0 for a single rank")
    args.out.mkdir(parents=True, exist_ok=True)
    metrics_dir = args.metrics_dir or args.out / "metrics"
    device_capacity_gib = device_memory_gib().get("device_total_gib")
    policy = Cosmos3OmniPolicy(
        backend=backend,
        selective_checkpointing=args.activation_checkpointing == "selective",
        selective_budget_gib=args.selective_budget_gib,
    )
    plugin = HybridParallelPlugin(
        tp_size=1,
        pp_size=1,
        sp_size=args.sp_size,
        enable_sequence_parallelism=args.sp_size > 1,
        sequence_parallelism_mode="all_to_all" if args.sp_size > 1 else None,
        zero_stage=args.zero_stage,
        precision="bf16",
        max_norm=GRAD_CLIP,
        custom_policy=policy,
        hsdp_shard_size=args.hsdp_shard_size,
        cast_inputs=args.cast_inputs,
        cast_buffers=args.cast_buffers,
    )
    unique_dp = dist.get_world_size(plugin.dp_group)
    dp_rank = dist.get_rank(plugin.dp_group)
    cp_leader = args.sp_size == 1 or dist.get_rank(plugin.sp_group) == 0
    dataset = DroidActionPolicyDataset(
        args.data,
        chunk_length=args.chunk_length,
        fps=args.fps,
        resolution=args.resolution,
        augment=True,
        max_episodes=args.max_episodes,
        keep_ranges=args.keep_ranges,
        success_only=args.success_only,
    )
    # Both strategies use shared memory for tensor storage. file_system only changes how handles are named;
    # it does not increase /dev/shm capacity. Size workers/batches and container shared memory accordingly.
    torch.multiprocessing.set_sharing_strategy(os.environ.get("COSMOS3_SHM_STRATEGY", "file_system"))
    dataloader = plugin.prepare_dataloader(
        dataset,
        batch_size=args.samples_per_rank,
        shuffle=False,
        drop_last=True,
        collate_fn=collate,
        num_workers=args.num_workers,
        seed=args.seed + dp_rank,
        distributed_sampler_cls=partial(torch.utils.data.DistributedSampler, drop_last=True),
        multiprocessing_context=args.mp_context if args.num_workers else None,
        persistent_workers=args.num_workers > 0,
    )
    if len(dataloader) == 0:
        raise ValueError(
            f"No full batch: dataset={len(dataset)}, independent_DP={unique_dp}, batch={args.samples_per_rank}"
        )
    model = build_model(args.checkpoint, args.reinit_action_head, args.action_head_from)
    model_config = model.config
    if args.activation_checkpointing == "full":
        model.enable_gradient_checkpointing()
    optimizer = build_optimizer(model, args.optimizer, args.adamw_mode, accelerator.name)
    booster = Booster(plugin=plugin)
    model, optimizer, _, dataloader, _ = booster.boost(model, optimizer, dataloader=dataloader)
    # The policy has now installed attention, FP32 timestep/sinusoidal wrappers and checkpointing.
    if args.compile_blocks:
        target = model.unwrap()
        target.layers = torch.nn.ModuleList(
            [torch.compile(layer, backend=compile_backend, fullgraph=True, dynamic=True) for layer in target.layers]
        )
    tokenizer = build_tokenizer(args.checkpoint) if cp_leader else None
    vae = None
    if cp_leader:
        aot_dir = (args.compile_vae_aot_dir or args.out / "aot_vae") if args.vae_compile == "aot" else None
        vae = build_vae(
            args.checkpoint,
            getattr(torch, args.vae_dtype),
            args.vae_chunk_frames,
            args.fuse_vae_norm,
            args.fast_vae_encoder,
            aot_dir=aot_dir,
            gate_rtol=args.vae_gate_rtol,
            gate_atol=args.vae_gate_atol,
            gate_relative_l2=args.vae_gate_relative_l2,
        ).to(device)
        if args.vae_compile == "jit":
            vae._encode = torch.compile(vae._encode, backend=vae_backend, dynamic=False)
    random.seed(args.seed + dp_rank)
    torch.manual_seed(args.seed + dp_rank)
    noise = torch.Generator().manual_seed(args.seed + dp_rank)
    model.train()
    optimizer.zero_grad()
    observers = [ConsoleObserver()]
    if args.wandb_project and args.wandb_mode != "disabled":
        observers.append(WandbObserver(args.wandb_project, args.wandb_run_name, mode=args.wandb_mode))
    metrics = TrainingMetrics(
        out_dir=metrics_dir,
        rank=coord.rank,
        world_size=coord.world_size,
        log_every=args.metrics_every,
        aggregate_observers=observers,
        detector=AnomalyDetector(device_capacity_gib=device_capacity_gib),
        write_aggregate=not args.no_aggregate_metrics,
        collective=args.collective_metrics,
    )
    target = model.unwrap()
    rank_identity = collect_rank_identity(device)
    manifest = {
        "args": vars(args),
        "world_size": coord.world_size,
        "env": {
            "torch": torch.__version__,
            "device": accelerator.name,
            **{
                name: package_version(name)
                for name in ("diffusers", "transformers", "torchvision", "av", "numpy", "pillow")
            },
        },
        "compiler": {"decoder": compile_backend, "vae_mode": args.vae_compile, "vae_backend": vae_backend},
        "attention": {
            "requested": args.attn_backend,
            "resolved": backend,
            "processor": type(policy.processor).__name__,
        },
        "precision": {
            "parameters": "bfloat16",
            "vae": args.vae_dtype,
            "cast_inputs": args.cast_inputs,
            "cast_buffers": args.cast_buffers,
            "buffers": {name: str(value.dtype) for name, value in target.named_buffers()},
        },
        "loss_objective": "droid_sample_modality_mean",
        "topology": parallel_topology(plugin, extra=rank_identity),
        "independent_dp_replicas": unique_dp,
        "effective_global_batch": args.samples_per_rank * args.grad_accum * unique_dp,
        "save_kind": "model_export",
        "curated_ranges": args.keep_ranges,
    }
    identity = collect_run_identity(args, run_name=args.run_name, run_id=args.run_id) if coord.rank == 0 else None
    if dist.is_initialized():
        identity_holder = [identity]
        dist.broadcast_object_list(identity_holder, src=0)
        identity = identity_holder[0]
    elif identity is None:
        identity = collect_run_identity(args, run_name=args.run_name, run_id=args.run_id)
    manifest = enrich_manifest(
        manifest,
        args=args,
        device=device,
        identity=identity,
        run_name=args.run_name,
        run_id=args.run_id,
        checkpoint_schedule={
            "model_export": {
                "every": args.save_every,
                "root": str(args.out),
                "pattern": "step-{step}",
                "async": bool(args.async_save),
                "format": "safetensors_sharded",
            },
            "resumable": None,
            "save_kind": "model_export",
        },
        log_path=args.log_path,
        heartbeat_seconds=args.heartbeat_seconds,
        metrics_every=args.metrics_every,
        log_every=args.log_every,
    )
    metrics.start(manifest)
    heartbeat = None
    if not args.no_heartbeat:
        heartbeat = TrainingHeartbeat(
            metrics_dir,
            coord.rank,
            device,
            args.heartbeat_seconds,
            run_id=manifest.get("run_id"),
            world_size=coord.world_size,
            local_rank=rank_identity.get("local_rank"),
            device_name=rank_identity.get("device_name"),
        ).start()
    ledger = (
        None
        if args.no_checkpoint_ledger or coord.rank != 0
        else CheckpointLedger(metrics_dir, rank=coord.rank, run_id=manifest.get("run_id"), world_size=coord.world_size)
    )
    watch = Stopwatch()
    iterator = None
    epoch = step = 0
    pending_exports = []
    completed = False
    run_started = time.perf_counter()
    last_values = None
    best_loss = None
    checkpoint_stats = {"count": 0, "bytes": 0}
    try:
        for step_index in range(args.max_iter):
            if heartbeat:
                heartbeat.update("data", step=step_index)
            record_now = step_index == 0 or (step_index + 1) % args.metrics_every == 0
            print_now = step_index == 0 or (step_index + 1) % args.log_every == 0
            if record_now:
                accelerator.synchronize()
            window_start = time.perf_counter()
            watch.reset(enabled=record_now)
            window = AccumulationWindow(count_samples=cp_leader)
            for microstep in range(args.grad_accum):
                wait_start = time.perf_counter()
                batch = None
                if cp_leader:
                    if iterator is None:
                        iterator = iter(dataloader)
                    try:
                        batch = next(iterator)
                    except StopIteration:
                        epoch += 1
                        dataloader.sampler.set_epoch(epoch)
                        iterator = iter(dataloader)
                        batch = next(iterator)
                wait_ms = (time.perf_counter() - wait_start) * 1e3
                inputs = targets = meta = None
                with watch.section("data"):
                    if cp_leader:
                        inputs, targets = pack_batch(
                            batch,
                            vae,
                            tokenizer,
                            model_config,
                            policy=policy,
                            num_frames=args.chunk_length + 1,
                            fps=args.fps,
                            resolution=args.resolution,
                            device=device,
                            generator=noise,
                            stopwatch=watch,
                            vae_encode_batch=args.vae_encode_batch,
                        )
                        inputs["_sample_ids"] = batch["sample_id"]
                        meta = policy.packed_meta
                    context = getattr(policy, "context_parallel", None)
                    if context is not None:
                        inputs, targets, meta = context.broadcast_pack(inputs, targets, meta, device=device)
                        policy.set_packed_meta(meta)
                        if args.cp_debug_identity:
                            context.validate_pack(
                                tokens=inputs["input_ids"], positions=inputs["position_ids"], payload=(inputs, targets)
                            )
                    inputs.pop("_sample_ids")
                if heartbeat:
                    heartbeat.update("forward", step=step_index, microstep=microstep + 1, microsteps=args.grad_accum)
                with watch.section("forward"):
                    out = model(**inputs)
                    raw_loss, components = compute_loss(out, targets, return_components=True)
                if heartbeat:
                    heartbeat.update("backward", step=step_index, microstep=microstep + 1, microsteps=args.grad_accum)
                with watch.section("backward"):
                    booster.backward(raw_loss / args.grad_accum, optimizer)
                window.add(meta.num_samples, meta, raw_loss, components, wait_ms)
            if args.async_save:
                booster.checkpoint_io.synchronize()
            if heartbeat:
                heartbeat.update("optimizer", step=step_index)
            with watch.section("optim"):
                optimizer.step()
                optimizer.zero_grad()
            step = step_index + 1
            if heartbeat:
                heartbeat.update("step_complete", step=step)
            dispatch_ms = (time.perf_counter() - window_start) * 1e3
            if record_now or print_now:
                values = window.loss_values()
                last_values = values
                if values.get("total") is not None:
                    best_loss = values["total"] if best_loss is None else min(best_loss, values["total"])
            if print_now:
                coord.print_on_master(
                    f"[step {step}] loss {values['total']:.6f} (v {values['vision']:.4f} a {values['action']:.4f})"
                )
            if record_now:
                accelerator.synchronize()
                step_ms = (time.perf_counter() - window_start) * 1e3
                timings = watch.read_ms()
                get_grad_norm = getattr(optimizer, "get_grad_norm", None)
                metrics.step(
                    step,
                    data={
                        "samples": window.samples,
                        "ar_tokens": window.ar_tokens,
                        "dm_tokens": window.dm_tokens,
                        "wait_ms": window.wait_ms,
                        "pack_ms": timings.get("data"),
                        "vae_ms": timings.get("vae"),
                        "epoch": epoch,
                    },
                    loss=values,
                    perf={
                        "step_ms": step_ms,
                        "host_dispatch_ms": dispatch_ms,
                        "timing_sources": watch.timing_sources,
                        "forward_ms": timings.get("forward"),
                        "backward_ms": timings.get("backward"),
                        "optim_ms": timings.get("optim"),
                    },
                    optim={
                        "grad_norm": get_grad_norm() if get_grad_norm else None,
                        **optimizer_learning_rates(optimizer),
                    },
                    mem=device_memory_gib(),
                )
            if step % args.save_every == 0:
                save_dir = args.out / f"step-{step}"
                checkpoint_id = None
                if ledger is not None:
                    checkpoint_id = ledger.begin(
                        step=step,
                        kind="model_export",
                        path=save_dir,
                        async_=args.async_save,
                        format_="safetensors_sharded",
                        schedule_every=args.save_every,
                    )
                try:
                    booster.save_model(
                        model, str(save_dir), shard=True, use_safetensors=True, use_async=args.async_save
                    )
                except Exception as exc:
                    if ledger is not None and checkpoint_id is not None:
                        ledger.fail(checkpoint_id, f"{type(exc).__name__}: {exc}")
                    raise
                if args.async_save:
                    pending_exports.append((save_dir, checkpoint_id))
                else:
                    fix_checkpoint_modes(save_dir, coord)
                    if ledger is not None and checkpoint_id is not None:
                        finished = ledger.end(checkpoint_id, status="complete")
                        checkpoint_stats["count"] += 1
                        checkpoint_stats["bytes"] += int(finished.get("bytes") or 0)
        completed = True
    finally:
        try:
            shutdown_dataloader(iterator)
        finally:
            if pending_exports:
                booster.checkpoint_io._sync_io()
                for save_dir, checkpoint_id in pending_exports:
                    fix_checkpoint_modes(save_dir, coord)
                    if ledger is not None and checkpoint_id is not None:
                        finished = ledger.end(checkpoint_id, status="complete")
                        checkpoint_stats["count"] += 1
                        checkpoint_stats["bytes"] += int(finished.get("bytes") or 0)
            if ledger is not None:
                ledger.complete_pending(status="complete" if completed else "aborted")
                ledger.close()
            if heartbeat:
                heartbeat.update("completed" if completed else "failed", step=step)
                heartbeat.close()
            memory = device_memory_gib()
            write_terminal(
                metrics_dir,
                coord.rank,
                {
                    "step": step,
                    "completed": completed,
                    "time": time.time(),
                    "duration_s": time.perf_counter() - run_started,
                    "last_phase": "completed" if completed else "failed",
                    "cleanup_warning": None,
                    "error": None,
                },
            )
            metrics.finish(
                {
                    "steps": step,
                    "completed": completed,
                    "duration_s": time.perf_counter() - run_started,
                    "session_id": getattr(metrics, "session_id", None),
                    "run_id": manifest.get("run_id"),
                    "last_loss": (last_values or {}).get("total"),
                    "best_loss": best_loss,
                    "peak_device_used_gib": (
                        heartbeat.peak if heartbeat is not None else memory.get("device_used_gib")
                    ),
                    "checkpoint_count": checkpoint_stats["count"],
                    "checkpoint_bytes": checkpoint_stats["bytes"],
                    "selective_checkpointing": get_cosmos3_selective_checkpoint_stats(target),
                }
            )
    if os.environ.get("COSMOS3_REPORT_PEAK_HBM"):
        print(f"[mem rank {coord.rank}] peak allocated {device_memory_gib().get('peak_gib', 0.0):.2f} GiB", flush=True)
    coord.print_on_master("done")


if __name__ == "__main__":
    main()
