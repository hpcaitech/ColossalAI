def advance_cursor(batches_in_epoch, epoch, batches_per_epoch):
    """Consume one microstep of the sampler stream; returns ``(cursor, epoch, wrapped)``.

    The cursor counts batches, not optimizer steps, because one step pulls ``grad_accum`` of
    them; the epoch advances exactly where the sampler stream wraps, so the saved position does
    not depend on which ranks pull batches.
    """
    batches_in_epoch += 1
    if batches_in_epoch >= batches_per_epoch:
        return 0, epoch + 1, True
    return batches_in_epoch, epoch, False


def flush_pending(pending, ledger, stats):
    """Publish every finished asynchronous generation. Collective: every rank calls this."""
    while pending:
        checkpoint, checkpoint_id = pending.pop(0)
        flush_checkpoint(checkpoint, ledger=ledger, checkpoint_id=checkpoint_id, stats=stats)


def fix_checkpoint_modes(save_dir: Path, coord: DistCoordinator):
    """Make finished model exports group-readable, after asynchronous writers have joined."""
    if coord.is_master():
        for path in save_dir.rglob("*"):
            os.chmod(path, 0o664 if path.is_file() else 0o775)


def main():
    # Before anything allocates: keep this rank, and the dataloader workers it later spawns, on the socket its NPU
    # sits on. Off unless COSMOS3_NUMA_PIN is set (see numa_affinity.py for the map and the measurements).
    pinned, pin_note = apply_affinity()
    if pinned and os.environ.get("LOCAL_RANK", "0") == "0":
        print(f"[numa] {pin_note}", flush=True)
    args = parse_args()
    accelerator = get_accelerator()
    if accelerator.name == "npu":
        importlib.import_module("torch_npu")
    backend = resolve_attention_backend(args.attn_backend, accelerator.name)
    compile_backend = resolve_compile_backend(args.compile_backend, accelerator.name) if args.compile_blocks else None
    vae_backend = (
        resolve_compile_backend(args.compile_vae_backend, accelerator.name) if args.vae_compile == "jit" else None
    )
    if args.vae_compile == "aot" and accelerator.name != "cuda":
        raise ValueError("VAE AOTInductor packages require CUDA")
    if args.optimizer == "adamw" and args.adamw_mode == "fused" and accelerator.name != "npu":
        raise ValueError("The fused AdamW arm requires an NPU")
    colossalai.launch_from_torch(backend=accelerator.communication_backend, seed=args.seed)
    coord = DistCoordinator()
    device = accelerator.get_current_device()
    if coord.world_size % args.sp_size:
        raise ValueError("--sp-size must divide world size")
    if args.zero_stage > 0 and coord.world_size == 1:
        raise ValueError("Use --zero-stage 0 for a single rank")
    args.out.mkdir(parents=True, exist_ok=True)
    metrics_dir = args.metrics_dir or args.out / "metrics"
    device_capacity_gib = device_memory_gib().get("device_total_gib")
    policy = Cosmos3OmniPolicy(
        backend=backend,
        selective_checkpointing=args.activation_checkpointing == "selective",
        selective_budget_gib=args.selective_budget_gib,
    )
    plugin = HybridParallelPlugin(
        tp_size=1,
        pp_size=1,
        sp_size=args.sp_size,
        enable_sequence_parallelism=args.sp_size > 1,
        sequence_parallelism_mode="all_to_all" if args.sp_size > 1 else None,
        zero_stage=args.zero_stage,
        zero_bucket_size_in_m=args.zero_bucket_size_m,
        precision="bf16",
        max_norm=GRAD_CLIP,
        custom_policy=policy,
        hsdp_shard_size=args.hsdp_shard_size,
        cast_inputs=args.cast_inputs,
        cast_buffers=args.cast_buffers,
        overlap_allgather=args.overlap_allgather,
    )
    unique_dp = dist.get_world_size(plugin.dp_group)
    dp_rank = dist.get_rank(plugin.dp_group)
    cp_leader = args.sp_size == 1 or dist.get_rank(plugin.sp_group) == 0
    # Both readers take the same arguments and return the same sample contract; upstream_dataset.py
    # documents where the seam between them sits and what was measured across it.
    # Both names are resolved from the module rather than imported here, so a test can substitute either
    # reader the same way. Importing upstream_dataset costs nothing by itself: it only reaches for
    # cosmos_framework when a reader is actually constructed.
    reader = UpstreamDroidDataset if args.dataset == "upstream" else DroidActionPolicyDataset
    dataset = reader(
        args.data,
        chunk_length=args.chunk_length,
        fps=args.fps,
        resolution=args.resolution,
        # A cached latent freezes whatever augmentation produced it, so the online transforms must be off on this
        # path; the cache itself already carries the augmented pixels.
        augment=args.image_augmentation == "torchvision" and args.latent_cache is None,
        max_episodes=args.max_episodes,
        keep_ranges=args.keep_ranges,
        success_only=args.success_only,
        action_cache=args.action_cache,
        video_content_pad=args.vae_content_pad,
        video_uint8=args.video_uint8,
    )
    # Which reader ran, and which cosmos_framework the copy resolved to, are read from the run rather than
    # inferred from the flag: on a host that also has the framework installed the installed one wins, and a
    # run that quietly used the other copy would be comparing something else.
    coord.print_on_master(f"[data] {len(dataset)} window(s) from reader {args.dataset!r}")
    coord.print_on_master(f"[data] pipeline from {report_pipeline_source()}")
    if args.latent_cache is not None:
        from examples.worldmodel.cosmos3.latent_cache import LatentCacheDataset

        dataset = LatentCacheDataset(dataset, args.latent_cache)
    # Both strategies use shared memory for tensor storage. file_system only changes how handles are named;
    # it does not increase /dev/shm capacity. Size workers/batches and container shared memory accordingly.
    checkpoint_root = args.out / "checkpoints"
    ckpt_config = checkpoint_config(args, plugin, unique_dp, len(dataset))
    resume_root = resume_state = None
    start_step = resume_epoch = resume_cursor = 0
    if args.resume is not None:
        # Validate before the model exists: the sampler needs the cursor at construction, and a
        # corrupted generation must be rejected before any weight is loaded.
        resume_root, resume_state = validate_checkpoint(args.resume, expected_config=ckpt_config)
        start_step = int(resume_state["step"])
        resume_epoch = int(resume_state["epoch"])
        resume_cursor = int(resume_state["sampler_cursor"])
    # Both the sampler's index stream and the DataLoader drop the last partial batch, so an epoch
    # is a whole number of batches; a cursor saved at an epoch boundary belongs to the next one.
    batches_per_epoch = (len(dataset) // unique_dp) // args.samples_per_rank
    if batches_per_epoch == 0:
        raise ValueError(
            f"No full batch: dataset={len(dataset)}, independent_DP={unique_dp}, batch={args.samples_per_rank}"
        )
    if resume_cursor >= batches_per_epoch:
        resume_epoch += resume_cursor // batches_per_epoch
        resume_cursor %= batches_per_epoch
    torch.multiprocessing.set_sharing_strategy(os.environ.get("COSMOS3_SHM_STRATEGY", "file_system"))
    dataloader = plugin.prepare_dataloader(
        dataset,
        batch_size=args.samples_per_rank,
        shuffle=False,
        drop_last=True,
        collate_fn=collate,
        num_workers=args.num_workers,
        worker_threads=args.worker_threads,
        seed=args.seed + dp_rank,
        distributed_sampler_cls=partial(
            ResumeDistributedSampler,
            drop_last=True,
            batch_size=args.samples_per_rank,
            start_batch=resume_cursor,
            start_epoch=resume_epoch,
        ),
        multiprocessing_context=args.mp_context if args.num_workers else None,
        persistent_workers=args.num_workers > 0,
        # Deepen the worker queue on request; PyTorch's default of 2 batches is what turns one slow batch into a
        # dataloader wait on the following step.
        **({"prefetch_factor": args.prefetch_factor} if args.prefetch_factor > 1 and args.num_workers else {}),
    )
    if len(dataloader) == 0:
        raise ValueError(
            f"No full batch: dataset={len(dataset)}, independent_DP={unique_dp}, batch={args.samples_per_rank}"
        )
    model = build_model(args.checkpoint, args.reinit_action_head, args.action_head_from)
    model_config = model.config
    # Derive the FLOPs scale from the checkpoint geometry once; the record then carries the number every
    # consumer can read instead of each consumer guessing a per-sample constant.
    flops_model = Cosmos3FlopsModel.from_config(model_config)
    if args.activation_checkpointing == "full":
        model.enable_gradient_checkpointing()
    optimizer = build_optimizer(model, args.optimizer, args.adamw_mode, accelerator.name)
    booster = Booster(plugin=plugin)
    model, optimizer, _, dataloader, _ = booster.boost(model, optimizer, dataloader=dataloader)
    # The policy has now installed attention, FP32 timestep/sinusoidal wrappers and checkpointing.
    if args.dit_sum_mean_norm and device.type == "npu":
        from examples.worldmodel.cosmos3.dit_norm_kernel import enable_sum_mean_norm

        enable_sum_mean_norm(model.unwrap(), verbose=True)
    if args.dit_norm_kernel and device.type == "npu":
        # After boost, so the patch lands on the modules the policy kept (it re-installs layer forwards).
        from examples.worldmodel.cosmos3.dit_norm_kernel import enable_dit_norm

        enable_dit_norm(model.unwrap(), verbose=True)
    if args.compile_blocks:
        target = model.unwrap()
        target.layers = torch.nn.ModuleList(
            [torch.compile(layer, backend=compile_backend, fullgraph=True, dynamic=True) for layer in target.layers]
        )
    tokenizer = build_tokenizer(args.checkpoint) if cp_leader else None
    vae = None
    # With a latent cache the VAE has nothing to do: its only job in the step was the encode, and that already
    # happened when the cache was written. Skipping the build also keeps the peak-memory number honest, since the
    # ~0.5 GiB of VAE weights would otherwise sit on the card during a run that never calls it.
    if cp_leader and args.latent_cache is None:
        aot_dir = (args.compile_vae_aot_dir or args.out / "aot_vae") if args.vae_compile == "aot" else None
        vae = build_vae(
            args.checkpoint,
            getattr(torch, args.vae_dtype),
            args.vae_chunk_frames,
            args.fuse_vae_norm,
            args.fast_vae_encoder,
            aot_dir=aot_dir,
            gate_rtol=args.vae_gate_rtol,
            gate_atol=args.vae_gate_atol,
            gate_relative_l2=args.vae_gate_relative_l2,
            norm_kernel=args.vae_norm_kernel,
        ).to(device)
        if args.vae_compile == "jit":
            vae._encode = torch.compile(vae._encode, backend=vae_backend, dynamic=False)
    random.seed(args.seed + dp_rank)
    torch.manual_seed(args.seed + dp_rank)
    noise = torch.Generator().manual_seed(args.seed + dp_rank)

    def capture_rank_state():
        return {"noise_generator": noise.get_state()}

    def restore_rank_state(extra):
        if not isinstance(extra, dict) or "noise_generator" not in extra:
            raise ValueError("Checkpoint has no rank noise generator state")
        noise.set_state(extra["noise_generator"])

    if resume_root is not None:
        # After the seeding above, so the restored streams are the ones the run continues from.
        apply_checkpoint(resume_root, resume_state, model, optimizer, on_rank_state=restore_rank_state)
    # Initialize the EMA after the resume: its shadow starts from the fp32 masters the run continues from.
    ema = PowerEMA(model, optimizer) if args.ema else None
    if ema is not None:
        held = sum(t.numel() for t in ema.shadow)
        coord.print_on_master(
            f"[ema] power EMA over {held / 1e9:.3f}B fp32 value(s) on this rank, from the {ema.source_kind}"
        )
    model.train()
    optimizer.zero_grad()
    observers = [ConsoleObserver()]
    if args.wandb_project and args.wandb_mode != "disabled":
        observers.append(WandbObserver(args.wandb_project, args.wandb_run_name, mode=args.wandb_mode))
    metrics = TrainingMetrics(
        out_dir=metrics_dir,
        rank=coord.rank,
        world_size=coord.world_size,
        log_every=args.metrics_every,
        aggregate_observers=observers,
        detector=AnomalyDetector(device_capacity_gib=device_capacity_gib),
        write_aggregate=not args.no_aggregate_metrics,
        collective=args.collective_metrics,
    )
    target = model.unwrap()
    rank_identity = collect_rank_identity(device)
    manifest = {
        "args": vars(args),
        "world_size": coord.world_size,
        "flops_model": flops_model.as_dict(),
        "env": {
            "torch": torch.__version__,
            "device": accelerator.name,
            **{
                name: resolve_version(name)
                for name in ("diffusers", "transformers", "torchvision", "av", "numpy", "pillow")
            },
        },
        "compiler": {"decoder": compile_backend, "vae_mode": args.vae_compile, "vae_backend": vae_backend},
        "attention": {
            "requested": args.attn_backend,
            "resolved": backend,
            "processor": type(policy.processor).__name__,
        },
        "precision": {
            "parameters": "bfloat16",
            "vae": args.vae_dtype,
            "cast_inputs": args.cast_inputs,
            "cast_buffers": args.cast_buffers,
            "buffers": {name: str(value.dtype) for name, value in target.named_buffers()},
        },
        "loss_objective": "droid_sample_modality_mean",
        "topology": parallel_topology(plugin, extra=rank_identity),
        "independent_dp_replicas": unique_dp,
        "effective_global_batch": args.samples_per_rank * args.grad_accum * unique_dp,
        "save_kind": "resumable_generation",
        "curated_ranges": args.keep_ranges,
    }
    identity = collect_run_identity(args, run_name=args.run_name, run_id=args.run_id) if coord.rank == 0 else None
    if dist.is_initialized():
        identity_holder = [identity]
        dist.broadcast_object_list(identity_holder, src=0)
        identity = identity_holder[0]
    elif identity is None:
        identity = collect_run_identity(args, run_name=args.run_name, run_id=args.run_id)
    manifest = enrich_manifest(
        manifest,
        args=args,
        device=device,
        identity=identity,
        run_name=args.run_name,
        run_id=args.run_id,
        checkpoint_schedule={
            "resumable": {
                "every": args.save_every,
                "root": str(checkpoint_root),
                "pattern": "checkpoint-{generation}",
                "async": bool(args.async_save),
                "format": "immutable_generation",
            },
            "save_kind": "resumable_generation",
            # Read by the monitor's checkpoint header; keep the flat keys it already understands.
            "save_every": args.save_every,
            "async_save": bool(args.async_save),
        },
        log_path=args.log_path,
        heartbeat_seconds=args.heartbeat_seconds,
        metrics_every=args.metrics_every,
        log_every=args.log_every,
    )
    metrics.start(manifest)
    heartbeat = None
    if not args.no_heartbeat:
        heartbeat = TrainingHeartbeat(
            metrics_dir,
            coord.rank,
            device,
            args.heartbeat_seconds,
            run_id=manifest.get("run_id"),
            world_size=coord.world_size,
            local_rank=rank_identity.get("local_rank"),
            device_name=rank_identity.get("device_name"),
        ).start()
    ledger = (
        None
        if args.no_checkpoint_ledger or coord.rank != 0
        else CheckpointLedger(metrics_dir, rank=coord.rank, run_id=manifest.get("run_id"), world_size=coord.world_size)
    )

    def save_ema(step: int) -> None:
        """Export the recipe's averaged weights beside the resumable generation.

        The plain weights are already in the generation; the average is what the recipe releases, so it is
        written to ``step-<n>/ema``.  The average is synchronous: it is produced while the working parameters
        hold values training is not using, so it must finish before they are put back.
        """
        if ema is None:
            return
        save_dir = args.out / f"step-{step}" / "ema"
        if args.async_save:
            booster.checkpoint_io._sync_io()
        with ema.applied():
            booster.save_model(model, str(save_dir), shard=True, use_safetensors=True)
        fix_checkpoint_modes(save_dir, coord)
        coord.print_on_master(f"[save] step {step} averaged weights -> {save_dir}")

    # The dashboard reads and writes <run>/control; the run directory is the one that holds metrics/, which is
    # what discovery sees, not necessarily --out (--metrics-dir may point elsewhere).
    control = RunControl(
        metrics_dir.parent,
        rank=coord.rank,
        world_size=coord.world_size,
        device=device,
        enabled=args.graceful_stop,
        every=args.stop_poll_every,
        poll_seconds=args.control_poll_seconds,
        run_started_at=manifest.get("started_at"),
        run_id=manifest.get("run_id"),
    ).start()
    watch = Stopwatch()
    iterator = None
    step = start_step
    epoch = resume_epoch
    batches_in_epoch = resume_cursor
    pending_checkpoints = []
    save_ms = None
    completed = False
    stopped = False
    run_started = time.perf_counter()
    last_values = None
    best_loss = None
    checkpoint_stats = {"count": 0, "bytes": 0}

    def save_generation(current_step, reason=None):
        """Publish the previous generation, then write the one for ``current_step``; returns its exposed cost."""
        flush_pending(pending_checkpoints, ledger, checkpoint_stats)
        checkpoint_id = None
        if ledger is not None:
            checkpoint_id = ledger.begin(
                step=current_step,
                kind="resumable_generation",
                path=checkpoint_root,
                async_=args.async_save,
                format_="immutable_generation",
                schedule_every=args.save_every,
                extra={"reason": reason} if reason else None,
            )
        save_started = time.perf_counter()
        try:
            pending_checkpoint = save_checkpoint(
                checkpoint_root,
                model,
                optimizer,
                {"step": current_step, "epoch": epoch, "sampler_cursor": batches_in_epoch, "config": ckpt_config},
                booster=booster,
                async_=args.async_save,
                on_rank_state=capture_rank_state,
                chmod=True,
            )
            if ema is not None:
                save_ema(current_step)
        except Exception as exc:
            if ledger is not None and checkpoint_id is not None:
                ledger.fail(checkpoint_id, f"{type(exc).__name__}: {exc}")
            raise
        cost_ms = (time.perf_counter() - save_started) * 1e3
        if args.async_save:
            pending_checkpoints.append((pending_checkpoint, checkpoint_id))
        elif ledger is not None and checkpoint_id is not None:
            finished = ledger.end(
                checkpoint_id,
                status="complete",
                path=pending_checkpoint.generation,
                generation=pending_checkpoint.generation.name,
            )
            checkpoint_stats["count"] += 1
            checkpoint_stats["bytes"] += int(finished.get("bytes") or 0)
        return cost_ms

    try:
        for step_index in range(start_step, args.max_iter):
            active_profiler = None
            if args.profile_step is not None and step_index == args.profile_step:
                if get_accelerator().name != "npu":
                    raise SystemExit("--profile-step needs the Ascend profiler")
                import torch_npu as _torch_npu

                profile_dir = args.out / "profile"
                profile_dir.mkdir(parents=True, exist_ok=True)
                active_profiler = _torch_npu.profiler.profile(
                    activities=[_torch_npu.profiler.ProfilerActivity.CPU, _torch_npu.profiler.ProfilerActivity.NPU],
                    on_trace_ready=_torch_npu.profiler.tensorboard_trace_handler(str(profile_dir)),
                    experimental_config=_torch_npu.profiler._ExperimentalConfig(
                        aic_metrics=_torch_npu.profiler.AiCMetrics.AiCoreNone
                    ),
                )
                active_profiler.start()
                print(f"[profile] step {step_index} -> {profile_dir}", flush=True)
            if heartbeat:
                heartbeat.update("data", step=step_index)
            record_now = step_index == 0 or (step_index + 1) % args.metrics_every == 0
            print_now = step_index == 0 or (step_index + 1) % args.log_every == 0
            if record_now:
                accelerator.synchronize()
            window_start = time.perf_counter()
            watch.reset(enabled=record_now)
            window = AccumulationWindow(count_samples=cp_leader)
            for microstep in range(args.grad_accum):
                wait_start = time.perf_counter()
                batch = None
                if cp_leader:
                    if iterator is None:
                        iterator = iter(dataloader)
                    try:
                        batch = next(iterator)
                    except StopIteration:
                        iterator = iter(dataloader)
                        batch = next(iterator)
                # Every rank keeps the same cursor: the epoch number advances where the sampler
                # stream wraps, so the saved state does not depend on which ranks pull batches.
                batches_in_epoch, epoch, wrapped = advance_cursor(batches_in_epoch, epoch, batches_per_epoch)
                if wrapped and cp_leader:
                    dataloader.sampler.set_epoch(epoch)
                wait_ms = (time.perf_counter() - wait_start) * 1e3
                inputs = targets = meta = None
                with watch.section("data"):
                    if cp_leader:
                        inputs, targets = pack_batch(
                            batch,
                            vae,
                            tokenizer,
                            model_config,
                            policy=policy,
                            num_frames=args.chunk_length + 1,
                            fps=args.fps,
                            resolution=args.resolution,
                            device=device,
                            generator=noise,
                            stopwatch=watch,
                            vae_encode_batch=args.vae_encode_batch,
                            latents=batch.get("latent"),
                        )
                        inputs["_sample_ids"] = batch["sample_id"]
                        meta = policy.packed_meta
                    context = getattr(policy, "context_parallel", None)
                    if context is not None:
                        inputs, targets, meta = context.broadcast_pack(inputs, targets, meta, device=device)
                        policy.set_packed_meta(meta)
                        if args.cp_debug_identity:
                            context.validate_pack(
                                tokens=inputs["input_ids"], positions=inputs["position_ids"], payload=(inputs, targets)
                            )
                    inputs.pop("_sample_ids")
                    if args.vae_norm_kernel and device.type == "npu":
                        # The VAE phase allocates one full activation per fused-norm call and the micro-batch
                        # sizes vary, so the allocator ends up holding a cached block per (shape, batch)
                        # combination: measured 19 GiB live against 56 GiB reserved on a 61 GiB card, climbing
                        # ~1.5 GiB per step (two-node A/B: 54.9 -> 58.3 -> 60.0 GiB). Return that slack once per
                        # step, while there is still headroom, instead of waiting for the card to fill up.
                        free_bytes, _total_bytes = torch.npu.mem_get_info()
                        keep_free = float(os.environ.get("COSMOS3_EMPTY_CACHE_GIB", "8")) * 2**30
                        if free_bytes < keep_free:
                            torch.npu.empty_cache()
                    if args.pack_hash and step_index == 0 and coord.rank == 0:
                        # Deterministic fingerprint of the packed step, for comparing two data paths that are
                        # supposed to produce the same inputs (online encode vs a pre-extracted latent cache).
                        # A loss comparison cannot settle that: the batch composition and the noise draw can
                        # differ between runs for reasons that have nothing to do with the latents.
                        print(
                            f"[pack-hash] inputs {_tensor_digest(inputs)} targets {_tensor_digest(targets)}",
                            flush=True,
                        )
                if heartbeat:
                    heartbeat.update("forward", step=step_index, microstep=microstep + 1, microsteps=args.grad_accum)
                with watch.section("forward"):
                    out = model(**inputs)
                    raw_loss, components = compute_loss(out, targets, return_components=True)
                if heartbeat:
                    heartbeat.update("backward", step=step_index, microstep=microstep + 1, microsteps=args.grad_accum)
                with watch.section("backward"):
                    booster.backward(raw_loss / args.grad_accum, optimizer)
                window.add(meta.num_samples, meta, raw_loss, components, wait_ms)
            if args.async_save:
                booster.checkpoint_io.synchronize()
            if heartbeat:
                heartbeat.update("optimizer", step=step_index)
            with watch.section("optim"):
                # The reference's order for one applied update: the schedule's rate for this zero-based
                # index, the step, then the EMA with that same index, then the gradients are cleared
                # (cosmos_framework/trainer/__init__.py:826-840). ``step_index`` is that zero-based index;
                # ``step`` below is it plus one and is for reporting.
                set_learning_rate(optimizer, step_index)
                optimizer.step()
                if ema is not None:
                    ema.update(step_index)
                optimizer.zero_grad()
            if active_profiler is not None:
                active_profiler.stop()
                print("[profile] stopped", flush=True)
            step = step_index + 1
            if heartbeat:
                heartbeat.update("step_complete", step=step)
            control.mark("step_complete", step=step)
            dispatch_ms = (time.perf_counter() - window_start) * 1e3
            if record_now or print_now:
                values = window.loss_values()
                last_values = values
                if values.get("total") is not None:
                    best_loss = values["total"] if best_loss is None else min(best_loss, values["total"])
            if print_now:
                coord.print_on_master(
                    f"[step {step}] loss {values['total']:.6f} (v {values['vision']:.4f} a {values['action']:.4f})"
                )
            if record_now:
                accelerator.synchronize()
                step_ms = (time.perf_counter() - window_start) * 1e3
                timings = watch.read_ms()
                get_grad_norm = getattr(optimizer, "get_grad_norm", None)
                sections = {}
                if save_ms is not None:
                    # Exposed save cost, reported once at the first record step after the save.
                    sections["ckpt"] = {"save_ms": save_ms, "async_pending": len(pending_checkpoints)}
                    save_ms = None
                vae_ms = timings.get("vae")
                selective_stats = (
                    get_cosmos3_selective_checkpoint_stats(target)
                    if args.activation_checkpointing == "selective"
                    else None
                )
                step_flops = cosmos3_step_flops(
                    flops_model,
                    samples=window.samples,
                    ar_tokens=window.ar_tokens,
                    dm_tokens=window.dm_tokens,
                    checkpointing=args.activation_checkpointing,
                    include_vae=vae_ms is not None,
                    selective_stats=selective_stats,
                )
                peak_tflops = ASCEND_910B2_CUBE_PEAK_TFLOPS
                flops_fields = {
                    "flops": step_flops["flops"],
                    "flops_forward": step_flops["flops_forward"],
                    "flops_backward": step_flops["flops_backward"],
                    "flops_vae": step_flops["flops_vae"],
                    "recompute_fraction": step_flops["recompute_fraction"],
                    "checkpointing_mode": args.activation_checkpointing,
                    "peak_tflops_per_npu": peak_tflops,
                    "tflops": (step_flops["flops"] / (step_ms / 1e3) / 1e12) if step_ms > 0 else None,
                    "mfu": step_mfu(step_ms, step_flops["flops"], coord.world_size, peak_tflops),
                    "mfu_forward": step_mfu(
                        timings.get("forward"), step_flops["flops_forward"], coord.world_size, peak_tflops
                    ),
                    "mfu_backward": step_mfu(
                        timings.get("backward"), step_flops["flops_backward"], coord.world_size, peak_tflops
                    ),
                    "mfu_vae": step_mfu(vae_ms, step_flops["flops_vae"], coord.world_size, peak_tflops),
                    "vae_ms": vae_ms,
                }
                metrics.step(
                    step,
                    **sections,
                    data={
                        "samples": window.samples,
                        "ar_tokens": window.ar_tokens,
                        "dm_tokens": window.dm_tokens,
                        "wait_ms": window.wait_ms,
                        "pack_ms": timings.get("data"),
                        "vae_ms": timings.get("vae"),
                        "epoch": epoch,
                    },
                    loss=values,
                    perf={
                        "step_ms": step_ms,
                        "host_dispatch_ms": dispatch_ms,
                        "timing_sources": watch.timing_sources,
                        "forward_ms": timings.get("forward"),
                        "backward_ms": timings.get("backward"),
                        "optim_ms": timings.get("optim"),
                        **flops_fields,
                    },
                    optim={
                        "grad_norm": get_grad_norm() if get_grad_norm else None,
                        **optimizer_learning_rates(optimizer),
                    },
                    mem=device_memory_gib(),
                )
            if step % args.save_every == 0:
                # Publish the previous generation before staging into the pinned buffers it reads.
                save_ms = save_generation(step)
            # Collective: every rank asks the same question at the same point of every step and leaves the
            # loop on the same iteration.  A rank-local exit would desynchronise the next gradient all-reduce.
            if control.boundary(step):
                stopped = True
                control.mark("stopping", step=step)
                break
        if stopped and step >= args.max_iter:
            # The request arrived at the last scheduled iteration: the run finished its schedule after all.
            stopped = False
        if stopped:
            # A stop is resumable from the iteration it happened at, so leave that exact generation behind
            # unless the periodic save just wrote it.  If either the save or the flush fails, the run did not
            # stop cleanly and must be reported as failed rather than as a clean stop.
            try:
                if step % args.save_every != 0:
                    save_ms = save_generation(step, reason="stop")
            except BaseException:
                stopped = False
                raise
        # Confirm the last generation before the run is reported complete.
        try:
            flush_pending(pending_checkpoints, ledger, checkpoint_stats)
        except BaseException:
            stopped = False
            raise
        completed = not stopped
    finally:
        # Cleanup runs even if shutdown_dataloader raises, and the shutdown exception still propagates after the
        # terminal/metrics files are written.  A monitor must see "failed", not a run that silently disappears.
        final_phase = "completed" if completed else ("stopped" if stopped else "failed")
        try:
            shutdown_dataloader(iterator)
        finally:
            if pending_checkpoints:
                try:
                    flush_pending(pending_checkpoints, ledger, checkpoint_stats)
                except Exception:
                    # Never let a failed flush hide the exception that brought us into this finally.
                    if completed or stopped:
                        raise
            if ledger is not None:
                ledger.complete_pending(status="complete" if completed else ("stopped" if stopped else "aborted"))
                ledger.close()
            if heartbeat:
                heartbeat.update(final_phase, step=step)
                heartbeat.close()
            control.mark(final_phase, step=step)
            control.close()
            memory = device_memory_gib()
            write_terminal(
                metrics_dir,
                coord.rank,
                {
                    "step": step,
                    "completed": completed,
                    "stopped": stopped,
                    "time": time.time(),
                    "duration_s": time.perf_counter() - run_started,
                    "last_phase": final_phase,
                    "cleanup_warning": None,
                    "error": None,
                },
            )
            metrics.finish(
                {
                    "steps": step,
                    "completed": completed,
                    "stopped": stopped,
                    "duration_s": time.perf_counter() - run_started,
                    "session_id": getattr(metrics, "session_id", None),
                    "run_id": manifest.get("run_id"),
                    "last_loss": (last_values or {}).get("total"),
                    "best_loss": best_loss,
                    "peak_device_used_gib": (
                        heartbeat.peak if heartbeat is not None else memory.get("device_used_gib")
                    ),
                    "checkpoint_count": checkpoint_stats["count"],
                    "checkpoint_bytes": checkpoint_stats["bytes"],
                    "selective_checkpointing": get_cosmos3_selective_checkpoint_stats(target),
                }
            )
    if os.environ.get("COSMOS3_REPORT_PEAK_HBM"):
        # Report every counter, not just the allocator's: `peak allocated` alone under-reads the card by the
        # reserved-but-idle blocks and by the device runtime's context, which is how a run can look comfortable and
        # then OOM. `device_used_gib` is the figure npu-smi shows.
        memory = device_memory_gib()
        print(
            f"[mem rank {coord.rank}] peak allocated {memory.get('peak_gib', 0.0):.2f} GiB"
            f" | peak reserved {memory.get('peak_reserved_gib', 0.0):.2f} GiB"
            f" | device used {memory.get('device_used_gib', 0.0):.2f} GiB"
            f" / {memory.get('device_total_gib', 0.0):.2f} GiB",
            flush=True,
        )
    coord.print_on_master("done")


if __name__ == "__main__":
    main()
